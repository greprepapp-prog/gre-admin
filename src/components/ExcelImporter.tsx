import { useMemo, useRef, useState } from 'react'
import * as XLSX from 'xlsx'
import { AlertCircle, CheckCircle2, Download, Loader2, Upload } from 'lucide-react'
import { supabase } from '../lib/supabase'

interface SheetConfig {
  sheetName: string
  label: string
  /** What this sheet writes to, shown in status/error messages. */
  targetDescription: string
  /** Performs whatever inserts this sheet needs. Returns an error message, or null on success. */
  importRows: (rows: ParsedRow[]) => Promise<string | null>
}

// The Clips sheet's raw headers (clip_no, video_path, Vocab, Explanation,
// GRE_example_1/2, ...) don't match lesson_segments' real columns
// (id, lesson_id, order_index, sentence_en, sentence_highlight, sentence_mn,
// video_url, focus_mn), so map them explicitly rather than inserting raw
// headers as-is. `id` is generated by the database — never sent.
//
// Note: this template has no separate localized sentence, so sentence_mn
// falls back to sentence_en. GRE_example_1/2 have no home in lesson_segments
// (they'd belong on a related segment_words row, which this importer does
// not create) and are intentionally dropped here.
function mapClipToLessonSegment(row: Record<string, string>): Record<string, string> {
  return {
    lesson_id: row.lesson_id ?? '',
    order_index: row.clip_no ?? '',
    video_url: row.video_path ?? '',
    sentence_en: row.sentence_en ?? '',
    sentence_highlight: row.vocab ?? '',
    sentence_mn: row.sentence_en ?? '',
    focus_mn: row.explanation ?? '',
  }
}

async function importClips(rows: ParsedRow[]): Promise<string | null> {
  const payload = rows.map((r) => mapClipToLessonSegment(r.data))
  const { error } = await supabase.from('lesson_segments').insert(payload)
  return error ? error.message : null
}

// Questions sheet: option_1_text..option_4_text + correct_option don't exist
// as columns on lesson_questions — they belong on child question_options
// rows, which need the parent question's generated id. So each row becomes
// one lesson_questions insert (getting back its id), then up to 4
// question_options inserts referencing that id.
async function importQuestions(rows: ParsedRow[]): Promise<string | null> {
  for (const row of rows) {
    const d = row.data
    const { data: inserted, error: questionError } = await supabase
      .from('lesson_questions')
      .insert({
        lesson_id: d.lesson_id ?? '',
        order_index: d.order_index ?? '',
        type: d.type || 'multiple-choice',
        prompt: d.prompt ?? '',
        word: d.word ?? '',
      })
      .select('id')
      .single()

    if (questionError || !inserted) {
      return `Row ${row.rowNumber}: ${questionError?.message ?? 'failed to create question'}`
    }

    const correctIndex = Number(d.correct_option) || 0
    const options = [1, 2, 3, 4]
      .map((n) => ({
        question_id: inserted.id as string,
        text: d[`option_${n}_text`] ?? '',
        is_correct: n === correctIndex,
        order_index: n,
      }))
      .filter((o) => o.text)

    if (options.length > 0) {
      const { error: optionsError } = await supabase.from('question_options').insert(options)
      if (optionsError) return `Row ${row.rowNumber} options: ${optionsError.message}`
    }
  }
  return null
}

// MatchPairs sheet: each row is one word/meaning pair, not a full question,
// but question_match_pairs still needs a parent lesson_questions row (a
// question_id FK). The sheet doesn't group pairs into questions itself, so
// this creates one type='match' question per distinct lesson_id and attaches
// all of that lesson's pairs to it.
async function importMatchPairs(rows: ParsedRow[]): Promise<string | null> {
  const byLesson = new Map<string, ParsedRow[]>()
  for (const row of rows) {
    const lessonId = row.data.lesson_id
    const group = byLesson.get(lessonId) ?? []
    group.push(row)
    byLesson.set(lessonId, group)
  }

  for (const [lessonId, group] of byLesson) {
    const { data: inserted, error: questionError } = await supabase
      .from('lesson_questions')
      .insert({
        lesson_id: lessonId,
        type: 'match',
        prompt: group[0].data.prompt || 'Match the words to their meanings',
      })
      .select('id')
      .single()

    if (questionError || !inserted) {
      return `Lesson ${lessonId}: ${questionError?.message ?? 'failed to create match question'}`
    }

    const pairs = group.map((row) => ({
      question_id: inserted.id as string,
      en: row.data.en ?? '',
      mn: row.data.mn ?? '',
      order_index: row.data.pair_order ?? '',
    }))

    const { error: pairsError } = await supabase.from('question_match_pairs').insert(pairs)
    if (pairsError) return `Lesson ${lessonId} pairs: ${pairsError.message}`
  }
  return null
}

// Typing sheet maps directly onto lesson_questions with type='typing' —
// the typed answer is graded against `word`, no child rows needed.
function mapTypingToQuestion(row: Record<string, string>): Record<string, string> {
  return {
    lesson_id: row.lesson_id ?? '',
    order_index: row.order_index ?? '',
    type: 'typing',
    prompt: row.prompt ?? '',
    word: row.answer ?? '',
  }
}

async function importTyping(rows: ParsedRow[]): Promise<string | null> {
  const payload = rows.map((r) => mapTypingToQuestion(r.data))
  const { error } = await supabase.from('lesson_questions').insert(payload)
  return error ? error.message : null
}

const SHEET_CONFIGS: SheetConfig[] = [
  { sheetName: 'Clips', label: 'Clips', targetDescription: 'lesson_segments', importRows: importClips },
  {
    sheetName: 'Questions',
    label: 'Questions',
    targetDescription: 'lesson_questions + question_options',
    importRows: importQuestions,
  },
  {
    sheetName: 'MatchPairs',
    label: 'Match Pairs',
    targetDescription: 'lesson_questions + question_match_pairs',
    importRows: importMatchPairs,
  },
  { sheetName: 'Typing', label: 'Typing', targetDescription: 'lesson_questions', importRows: importTyping },
]

const SAMPLE_TEMPLATE_URL = '/lesson_001_005_content.xlsx'

interface ParsedRow {
  rowNumber: number
  data: Record<string, string>
  hasLessonId: boolean
}

interface ParsedSheet {
  config: SheetConfig
  columns: string[]
  rows: ParsedRow[]
}

type SheetStatus = 'pending' | 'importing' | 'success' | 'error'

function normalizeKey(key: string): string {
  return key.trim().toLowerCase().replace(/\s+/g, '_')
}

function normalizeValue(value: unknown): string {
  if (value === null || value === undefined) return ''
  return String(value).trim()
}

function isRealColumn(key: string): boolean {
  return key.length > 0 && !key.startsWith('__empty')
}

function parseSheet(workbook: XLSX.WorkBook, config: SheetConfig): ParsedSheet {
  const sheet = workbook.Sheets[config.sheetName]
  const rawRows = XLSX.utils.sheet_to_json<Record<string, unknown>>(sheet, { defval: '' })

  const columnSet = new Set<string>()
  const rows: ParsedRow[] = rawRows.map((raw, i) => {
    const data: Record<string, string> = {}
    for (const [key, value] of Object.entries(raw)) {
      const normalizedKey = normalizeKey(key)
      if (!isRealColumn(normalizedKey)) continue
      data[normalizedKey] = normalizeValue(value)
      columnSet.add(normalizedKey)
    }
    return { rowNumber: i + 2, data, hasLessonId: Boolean(data.lesson_id) }
  })

  return { config, columns: Array.from(columnSet), rows }
}

export function ExcelImporter() {
  const [sheets, setSheets] = useState<ParsedSheet[]>([])
  const [activeSheet, setActiveSheet] = useState<string>(SHEET_CONFIGS[0].sheetName)
  const [fileName, setFileName] = useState<string | null>(null)
  const [parseError, setParseError] = useState<string | null>(null)
  const [importing, setImporting] = useState(false)
  const [sheetStatus, setSheetStatus] = useState<Record<string, SheetStatus>>({})
  const [sheetError, setSheetError] = useState<Record<string, string>>({})
  const [allDone, setAllDone] = useState(false)
  const fileInputRef = useRef<HTMLInputElement>(null)

  const totalValidRows = useMemo(
    () => sheets.reduce((sum, s) => sum + s.rows.filter((r) => r.hasLessonId).length, 0),
    [sheets],
  )

  function reset() {
    setSheets([])
    setFileName(null)
    setParseError(null)
    setSheetStatus({})
    setSheetError({})
    setAllDone(false)
    if (fileInputRef.current) fileInputRef.current.value = ''
  }

  async function handleFileChange(e: React.ChangeEvent<HTMLInputElement>) {
    const file = e.target.files?.[0]
    if (!file) return

    reset()
    setFileName(file.name)

    try {
      const buffer = await file.arrayBuffer()
      const workbook = XLSX.read(buffer, { type: 'array' })

      const missingSheets = SHEET_CONFIGS.filter((c) => !workbook.SheetNames.includes(c.sheetName))
      if (missingSheets.length > 0) {
        setParseError(
          `Missing required sheet(s): ${missingSheets.map((c) => c.sheetName).join(', ')}. ` +
            `Expected sheets: ${SHEET_CONFIGS.map((c) => c.sheetName).join(', ')}.`,
        )
        return
      }

      const parsedSheets = SHEET_CONFIGS.map((config) => parseSheet(workbook, config))
      setSheets(parsedSheets)
      setActiveSheet(parsedSheets[0].config.sheetName)
    } catch (err) {
      setParseError(err instanceof Error ? err.message : 'Failed to parse workbook.')
    }
  }

  async function handleImport() {
    if (sheets.length === 0) return
    setImporting(true)
    setAllDone(false)

    const initialStatus: Record<string, SheetStatus> = {}
    for (const s of sheets) initialStatus[s.config.sheetName] = 'pending'
    setSheetStatus(initialStatus)
    setSheetError({})

    let hadError = false

    for (const sheet of sheets) {
      const validRows = sheet.rows.filter((r) => r.hasLessonId)
      setSheetStatus((prev) => ({ ...prev, [sheet.config.sheetName]: 'importing' }))

      if (validRows.length === 0) {
        setSheetStatus((prev) => ({ ...prev, [sheet.config.sheetName]: 'success' }))
        continue
      }

      const errorMessage = await sheet.config.importRows(validRows)

      if (errorMessage) {
        hadError = true
        setSheetStatus((prev) => ({ ...prev, [sheet.config.sheetName]: 'error' }))
        setSheetError((prev) => ({ ...prev, [sheet.config.sheetName]: errorMessage }))
      } else {
        setSheetStatus((prev) => ({ ...prev, [sheet.config.sheetName]: 'success' }))
      }
    }

    setImporting(false)
    setAllDone(!hadError)
  }

  const active = sheets.find((s) => s.config.sheetName === activeSheet)

  return (
    <div className="space-y-6">
      <div>
        <h2 className="text-base font-semibold text-slate-900">Import lesson content</h2>
        <p className="mt-1 text-sm text-slate-500">
          Upload the lesson workbook (.xlsx) with sheets Clips, Questions, MatchPairs, and Typing. Nothing is
          written to Supabase until you review the preview below and confirm.
        </p>
      </div>

      <div className="flex flex-wrap items-center gap-3">
        <label className="inline-flex cursor-pointer items-center gap-2 rounded-md border border-slate-300 bg-white px-4 py-2 text-sm font-medium text-slate-700 hover:bg-slate-50">
          <Upload className="h-4 w-4" />
          Choose workbook
          <input
            ref={fileInputRef}
            type="file"
            accept=".xlsx"
            className="hidden"
            onChange={handleFileChange}
          />
        </label>

        <a
          href={SAMPLE_TEMPLATE_URL}
          download
          className="inline-flex items-center gap-2 rounded-md border border-slate-300 bg-white px-4 py-2 text-sm font-medium text-slate-700 hover:bg-slate-50"
        >
          <Download className="h-4 w-4" />
          Download Sample Template (.xlsx)
        </a>

        {fileName && <span className="text-sm text-slate-500">{fileName}</span>}
        {sheets.length > 0 && (
          <button
            type="button"
            onClick={reset}
            className="text-sm font-medium text-slate-500 underline hover:text-slate-700"
          >
            Clear
          </button>
        )}
      </div>

      {parseError && (
        <div className="flex items-center gap-2 rounded-md border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-700">
          <AlertCircle className="h-4 w-4 shrink-0" />
          {parseError}
        </div>
      )}

      {sheets.length > 0 && (
        <>
          <div className="flex flex-wrap gap-4 text-sm">
            {sheets.map((s) => {
              const validCount = s.rows.filter((r) => r.hasLessonId).length
              const missingCount = s.rows.length - validCount
              return (
                <span key={s.config.sheetName} className="inline-flex items-center gap-1.5 text-slate-600">
                  <span className="font-medium text-slate-900">{s.config.label}:</span> {s.rows.length} rows
                  {missingCount > 0 && (
                    <span className="text-amber-700">({missingCount} missing lesson_id)</span>
                  )}
                </span>
              )
            })}
          </div>

          <div className="border-b border-slate-200">
            <nav className="-mb-px flex gap-4">
              {sheets.map((s) => (
                <button
                  key={s.config.sheetName}
                  type="button"
                  onClick={() => setActiveSheet(s.config.sheetName)}
                  className={
                    activeSheet === s.config.sheetName
                      ? 'border-b-2 border-slate-900 px-1 py-2 text-sm font-medium text-slate-900'
                      : 'border-b-2 border-transparent px-1 py-2 text-sm font-medium text-slate-500 hover:text-slate-700'
                  }
                >
                  {s.config.label}
                  {sheetStatus[s.config.sheetName] === 'importing' && (
                    <Loader2 className="ml-1.5 inline h-3.5 w-3.5 animate-spin" />
                  )}
                  {sheetStatus[s.config.sheetName] === 'success' && (
                    <CheckCircle2 className="ml-1.5 inline h-3.5 w-3.5 text-emerald-600" />
                  )}
                  {sheetStatus[s.config.sheetName] === 'error' && (
                    <AlertCircle className="ml-1.5 inline h-3.5 w-3.5 text-red-600" />
                  )}
                </button>
              ))}
            </nav>
          </div>

          {active && sheetError[active.config.sheetName] && (
            <div className="flex items-center gap-2 rounded-md border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-700">
              <AlertCircle className="h-4 w-4 shrink-0" />
              Import failed for {active.config.label} → {active.config.targetDescription}:{' '}
              {sheetError[active.config.sheetName]}
            </div>
          )}

          {active && (
            <div className="overflow-x-auto rounded-md border border-slate-200">
              <table className="min-w-full divide-y divide-slate-200 text-sm">
                <thead className="bg-slate-50">
                  <tr>
                    <th className="px-3 py-2 text-left font-medium text-slate-500">Row</th>
                    {active.columns.map((col) => (
                      <th key={col} className="px-3 py-2 text-left font-medium text-slate-500">
                        {col}
                      </th>
                    ))}
                    <th className="px-3 py-2 text-left font-medium text-slate-500">Status</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100">
                  {active.rows.map((row) => (
                    <tr key={row.rowNumber} className={!row.hasLessonId ? 'bg-amber-50' : undefined}>
                      <td className="px-3 py-2 text-slate-400">{row.rowNumber}</td>
                      {active.columns.map((col) => (
                        <td key={col} className="px-3 py-2 text-slate-700">
                          {row.data[col] || '(empty)'}
                        </td>
                      ))}
                      <td className="px-3 py-2">
                        {row.hasLessonId ? (
                          <span className="inline-flex items-center gap-1 text-emerald-700">
                            <CheckCircle2 className="h-3.5 w-3.5" /> Valid
                          </span>
                        ) : (
                          <span className="inline-flex items-center gap-1 text-amber-700">
                            <AlertCircle className="h-3.5 w-3.5" /> Missing lesson_id
                          </span>
                        )}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}

          <button
            type="button"
            onClick={handleImport}
            disabled={totalValidRows === 0 || importing}
            className="inline-flex items-center gap-2 rounded-md bg-slate-900 px-4 py-2 text-sm font-medium text-white hover:bg-slate-800 disabled:cursor-not-allowed disabled:opacity-50"
          >
            {importing && <Loader2 className="h-4 w-4 animate-spin" />}
            {importing ? 'Importing…' : `Import ${totalValidRows} valid row(s) across ${sheets.length} sheets`}
          </button>

          {allDone && (
            <div className="flex items-center gap-2 rounded-md border border-emerald-200 bg-emerald-50 px-4 py-3 text-sm text-emerald-700">
              <CheckCircle2 className="h-4 w-4 shrink-0" />
              All sheets imported successfully.
            </div>
          )}
        </>
      )}
    </div>
  )
}
